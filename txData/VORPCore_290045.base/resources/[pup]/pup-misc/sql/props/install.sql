-- pup-misc / props | install.sql
--
-- Creates:  prop_offsets (per-character /pa offsets for a worn prop)
-- Items:    every wearable prop in config/props/props.lua, plus pomade (pup-misc/pomade)
-- Requires: VORP core tables items and characters (charidentifier), with item_group row 1 and
--           item_rarity rows 1 and 5 present. A missing group or rarity row makes INSERT IGNORE
--           skip the item without an error.
--
-- server/props/main.lua also creates prop_offsets and re-syncs label, limit and usable for every
-- prop item on start. Importing this first means the items exist before vorp_inventory caches
-- the items table on a first boot.
-- Safe to run more than once.

-- the offset columns MUST be FLOAT: an INT copy rounds every offset to 0 on save
