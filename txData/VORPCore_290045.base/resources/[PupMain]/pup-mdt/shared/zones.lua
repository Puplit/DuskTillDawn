local function toSigned(h)
    h = math.tointeger(tonumber(h)) or 0
    h = h & 0xFFFFFFFF
    if h >= 0x80000000 then h = h - 0x100000000 end
    return h
end

function PupMdtZones.nameFromHash(hash)
    if not hash or hash == 0 or hash == false then return nil end
    return PupMdtZones.byHash[toSigned(hash)]
end

local function xyz(c)
    if type(c) ~= 'table' and type(c) ~= 'vector3' and type(c) ~= 'vector4' then return nil end
    local x, y, z = tonumber(c.x or c[1]), tonumber(c.y or c[2]), tonumber(c.z or c[3])
    if not x or not y then return nil end
    return x, y, z or 0.0
end

local function dist2d(x1, y1, x2, y2)
    local dx, dy = x1 - x2, y1 - y2
    return math.sqrt(dx * dx + dy * dy)
end

-- '<Town>', 'Near <Town>', a landmark, or 'Unknown Zone'
function PupMdtZones.nameFromCoords(coords)
    local x, y = xyz(coords)
    if not x then return PupMdtZones.unknown end
    if x == 0 and y == 0 then return PupMdtZones.unknown end
    for _, l in ipairs(PupMdtZones.landmarks) do
        if dist2d(x, y, l.coords.x, l.coords.y) <= l.radius then return l.name end
    end
    local best, bestD = nil, math.huge
    for _, t in ipairs(PupMdtZones.towns) do
        local d = dist2d(x, y, t.coords.x, t.coords.y)
        if d <= t.radius then return t.name end
        if d < bestD then best, bestD = t, d end
    end
    if best and bestD <= PupMdtZones.nearRange then return 'Near ' .. best.name end
    return PupMdtZones.unknown
end
