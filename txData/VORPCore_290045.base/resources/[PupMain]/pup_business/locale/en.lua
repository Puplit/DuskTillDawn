-- L('key', ...) -> the formatted text, or the key itself when it is missing
function L(key, ...)
    local s = Locale[key]
    if not s then return key end
    if select('#', ...) == 0 then return s end
    local ok, out = pcall(string.format, s, ...)
    return ok and out or s
end
